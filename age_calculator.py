# -*- coding: utf-8 -*-
"""
age_calculator.py — определяет "возрастную категорию" машины для
калькулятора таможни (customs_calculator.py).

Почему это отдельная функция, а не просто "на глаз"?
От возраста напрямую зависит и коэффициент утильсбора, и ставка ЕТС —
ошибиться тут значит посчитать пошлину неправильно (а это реальные деньги).
Возраст считается от ГОДА ВЫПУСКА машины, а не от года покупки/публикации
объявления — это важно не перепутать.

ВАЖНО (найдено 2026-07): наивная разница календарных лет (current_year -
manufacture_year) — НЕ то же самое, что "сколько месяцев реально прошло".
Машина, выпущенная в декабре 2023, к июлю 2026 по календарным годам даёт
"3 года" (2026-2023), хотя реально прошло только 2 года 7 месяцев — то есть
она должна быть ещё в категории 'u3' (дороже), а не '35' (дешевле).
И наоборот: машина, выпущенная в январе 2021, к июлю 2026 даёт наивно "5
лет" (укладывается в '35'), хотя реально прошло 5 лет 6 месяцев — уже '57'.
Обе ошибки — реальные деньги, поэтому возраст считается по месяцам, если
известен месяц выпуска (не только год — см. encar_scraper.py/charancha_
scraper.py/used_car_scraper.py, там месяц уже извлекается из сырых данных).

Категории (те же, что использует customs_calc.html):
    'u3' — младше 3 лет
    '35' — от 3 до 5 лет
    '57' — от 5 до 7 лет
    'o7' — старше 7 лет
"""

import datetime


def age_bucket_from_year(manufacture_year: int, manufacture_month: int | None = None) -> str:
    """
    Превращает год (и, если известен, месяц) выпуска машины в возрастную
    категорию для калькулятора — см. докстринг файла про то, почему просто
    "текущий год минус год выпуска" недостаточно точно.

    Args:
        manufacture_year: год выпуска, например 2022.
        manufacture_month: месяц выпуска (1-12), если известен. Если
            неизвестен — используется декабрь (12) как консервативное
            допущение: это делает машину МАКСИМАЛЬНО МОЛОДОЙ из возможных
            для этого года (меньше всего времени якобы прошло) — при
            неизвестном месяце нельзя случайно занизить возраст и выдать
            более дешёвую (и потенциально неверную) категорию, чем
            полагается по факту. Ошибка в эту сторону — цена в посте выше
            реальной (не страшно), а не ниже (страшно — обманутое ожидание
            клиента при реальном таможенном оформлении).

    Returns:
        'u3' / '35' / '57' / 'o7' — см. описание категорий выше.
    """
    today = datetime.date.today()
    month = manufacture_month if manufacture_month else 12
    elapsed_months = (today.year - manufacture_year) * 12 + (today.month - month)

    if elapsed_months < 36:
        return "u3"
    if elapsed_months <= 60:
        return "35"
    if elapsed_months <= 84:
        return "57"
    return "o7"


