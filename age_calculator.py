# -*- coding: utf-8 -*-
"""
age_calculator.py — определяет "возрастную категорию" машины для
калькулятора таможни (customs_calculator.py).

Почему это отдельная функция, а не просто "на глаз"?
От возраста напрямую зависит и коэффициент утильсбора, и ставка ЕТС —
ошибиться тут значит посчитать пошлину неправильно (а это реальные деньги).
Возраст считается от ГОДА ВЫПУСКА машины, а не от года покупки/публикации
объявления — это важно не перепутать.

Категории (те же, что использует customs_calc.html):
    'u3' — младше 3 лет
    '35' — от 3 до 5 лет
    '57' — от 5 до 7 лет
    'o7' — старше 7 лет
"""

import datetime


def age_bucket_from_year(manufacture_year: int) -> str:
    """
    Превращает год выпуска машины в возрастную категорию для калькулятора.

    Args:
        manufacture_year: год выпуска, например 2022.

    Returns:
        'u3' / '35' / '57' / 'o7' — см. описание категорий выше.
    """
    current_year = datetime.date.today().year
    age_years = current_year - manufacture_year

    if age_years < 3:
        return "u3"
    if age_years <= 5:
        return "35"
    if age_years <= 7:
        return "57"
    return "o7"


def age_bucket_for_new_catalog_car() -> str:
    """
    Для машин из каталога НОВЫХ авто у дилера (когда точный год выпуска
    неизвестен, но мы точно знаем, что это текущая модель) — всегда
    "младше 3 лет". Вынесено в отдельную функцию, чтобы было явно видно
    ПОЧЕМУ здесь всегда 'u3', а не потому что "забыли посчитать".
    """
    return "u3"
