# -*- coding: utf-8 -*-
"""
brand_names_ko.py — маленький общий словарь "английское название марки ->
корейское", как его пишут на корейских автомобильных сайтах/в гос.
документах (OnBid, Charancha и т.д.). Многие такие сайты не понимают
латиницу в поле марки (подтверждено вживую на OnBid: "Audi" -> 0
результатов, "아우디" -> находит), поэтому нужен перевод перед запросом.

Пополняется по мере добавления новых брендов в target_models.json —
только те бренды, которые реально встречались. Если бренда нет в словаре —
используется исходный текст как есть (лучше попробовать латиницей, чем
упасть с ошибкой).
"""

BRAND_KO = {
    "audi": "아우디",
    "volkswagen": "폭스바겐",
    "vw": "폭스바겐",
    "kia": "기아",
    "hyundai": "현대",
    "bmw": "BMW",
    "mercedes-benz": "벤츠",
    "mercedes": "벤츠",
    "renault": "르노코리아(삼성)",
    "genesis": "제네시스",
    "chevrolet": "쉐보레(GM대우)",
}


def to_korean(brand: str) -> str:
    """Возвращает корейское название марки, если оно известно, иначе — исходный текст."""
    return BRAND_KO.get(brand.strip().lower(), brand)


# Обратный словарь (корейское -> английское), для broad-режима (см.
# broad_collector.py): там бренд не задан заранее (нет target_models.json
# записи), поэтому сырой корейский текст с сайта (kbchachacha, Charancha)
# нужно перевести обратно в читаемое название для поста. Явный список (не
# автогенерация из BRAND_KO) — там на одно корейское название иногда
# приходится несколько английских ключей (vw/volkswagen, mercedes/
# mercedes-benz) и порядок недетерминированно решал бы, какое "красивее".
_KO_TO_BRAND = {
    "아우디": "Audi",
    "폭스바겐": "Volkswagen",
    "기아": "Kia",
    "현대": "Hyundai",
    "벤츠": "Mercedes-Benz",
    "르노코리아(삼성)": "Renault",
    "제네시스": "Genesis",
    "쉐보레(GM대우)": "Chevrolet",
}


def from_korean(brand_ko: str) -> str:
    """Возвращает английское название марки по корейскому, если известно,
    иначе — исходный (корейский) текст как есть."""
    return _KO_TO_BRAND.get(brand_ko.strip(), brand_ko)


# То же самое, но для НАЗВАНИЙ МОДЕЛЕЙ — некоторые корейские сайты (Charancha,
# kbchachacha) хранят модель как корейскую транслитерацию, а не латиницей
# (напр. Volkswagen Tiguan -> "티구안"), в отличие от моделей-аббревиатур
# (K3, Q3, X6), которые обычно остаются как есть. Пополняется по мере
# необходимости — если модели нет в словаре, используется исходный текст.
MODEL_KO = {
    "tiguan": "티구안",
    "sonata": "쏘나타",
}


def model_to_korean(model: str) -> str:
    """Возвращает корейскую транслитерацию названия модели, если известна,
    иначе — исходный текст (для моделей-аббревиатур типа K3/Q3 это и есть
    правильный ответ — их не транслитерируют)."""
    return MODEL_KO.get(model.strip().lower(), model)
