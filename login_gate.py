# -*- coding: utf-8 -*-
"""
login_gate.py — общий примитив для source-адаптеров логин-площадок
(AJ/Glovis/HeyDealer/KCar/Lotte). Правило проекта: адаптер НИКОГДА не
логинится сам по себе молча на реальный (платный) аккаунт — только
переиспользует уже сохранённую валидную сессию. Если сессии нет/она
истекла, адаптер поднимает LoginRequiredError вместо того, чтобы тихо
запускать Playwright-логин.

model_search.py ловит именно это исключение отдельно от прочих ошибок и
останавливает конкретно этот источник, требуя явного подтверждения
пользователя на ЭТОТ запуск (--confirm-login <source>), прежде чем адаптер
получит право сам залогиниться (через target["allow_fresh_login"]).
"""


class LoginRequiredError(RuntimeError):
    """Сохранённая сессия невалидна/отсутствует, а свежий логин не подтверждён
    явно на этот запуск (target.get("allow_fresh_login") не True)."""
    pass
