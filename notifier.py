# -*- coding: utf-8 -*-
"""
notifier.py — отправляет короткое уведомление в твой личный Telegram-чат,
если во время работы бота что-то пошло не так.

Зачем это нужно, если у нас уже есть логирование в файл?
Файл лога ты увидишь, только если сам зайдёшь и откроешь его. А бот, скорее
всего, будет работать по расписанию без присмотра (см. GitHub Actions) —
если сайт вдруг перестанет открываться или токен протухнет, ты узнаешь
об этом только тогда, когда сам решишь проверить лог. Уведомление в
Telegram сообщает о проблеме СРАЗУ, как только она произошла.

Это НАМЕРЕННО отдельный, максимально простой файл — не переиспользует
telegram_publisher.py, чтобы уведомления об ошибках работали даже если
что-то сломалось в основном коде публикации (меньше общих зависимостей —
меньше шансов, что уведомление само не отправится из-за той же поломки).
"""

import logging
import requests

import config

logger = logging.getLogger("notifier")


def notify_error(message: str) -> None:
    """
    Отправляет сообщение об ошибке в личный чат администратора (config.ADMIN_CHAT_ID).

    Эта функция НАМЕРЕННО "тихая" — если сама отправка уведомления не
    удалась (нет интернета, неправильный chat_id и т.п.), она просто
    запишет это в лог и НЕ прервёт программу. Уведомление об ошибке —
    это "бонус", а не критичная часть работы бота; ронять всё из-за
    того, что не получилось пожаловаться, было бы странно.

    Args:
        message: текст уведомления (коротко опиши, что случилось).
    """
    if not config.ADMIN_CHAT_ID or not config.BOT_TOKEN:
        # Администратор не настроил уведомления — просто пишем в лог
        # и не пытаемся ничего слать.
        logger.info(f"(уведомление не отправлено, ADMIN_CHAT_ID не задан): {message}")
        return

    try:
        url = f"https://api.telegram.org/bot{config.BOT_TOKEN}/sendMessage"
        text = f"⚠️ auto_dealer_bot — ошибка:\n\n{message}"
        response = requests.post(
            url,
            json={"chat_id": config.ADMIN_CHAT_ID, "text": text},
            timeout=15,
        )
        if response.ok:
            logger.info("Уведомление об ошибке отправлено администратору")
        else:
            logger.warning(f"Не удалось отправить уведомление: {response.status_code} {response.text}")
    except requests.RequestException as error:
        # Намеренно НЕ поднимаем исключение дальше — см. докстринг выше.
        logger.warning(f"Не удалось отправить уведомление об ошибке (сеть): {error}")
